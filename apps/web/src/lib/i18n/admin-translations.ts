const ADMIN_AR_PATTERNS: Array<[RegExp, string]> = [
  [/^Admin \/ (.+)$/i, 'لوحة التحكم / $1'],
  [/^Saved \(v(\d+)\)$/i, 'تم الحفظ (إصدار $1)'],
  [/^Revision #(\d+)$/i, 'الإصدار #$1'],
  [/^Rollback Live to #(\d+)$/i, 'تراجع مباشر إلى الإصدار #$1'],
  [/^Save failed:\s*(.+)$/i, 'فشل الحفظ: $1'],
];

const ADMIN_CI_MAP = new Map<string, string>();
for (const [k, v] of Object.entries(ADMIN_AR_EXACT)) {
  ADMIN_CI_MAP.set(k.toLowerCase(), v);
}

export function translateAdminToArabic(text: string): string | null {
  const trimmed = text.trim();
  if (!trimmed) return null;

  const exact = ADMIN_AR_EXACT[trimmed] ?? ADMIN_CI_MAP.get(trimmed.toLowerCase());
  if (exact) {
    return text.replace(trimmed, exact);
  }

  for (const [regex, replacement] of ADMIN_AR_PATTERNS) {
    const match = trimmed.match(regex);
    if (match) {
      let out = trimmed.replace(regex, replacement);
      // Translate captured suffix if it matches an admin nav label
      if (match[1]) {
        const inner = ADMIN_AR_EXACT[match[1].trim()] ?? ADMIN_CI_MAP.get(match[1].trim().toLowerCase());
        if (inner) {
          out = out.replace(match[1], inner);
        }
      }
      return text.replace(trimmed, out);
    }
  }

  return null;
}
